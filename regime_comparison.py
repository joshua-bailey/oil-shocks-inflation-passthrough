def plot_state_irf(sd_df, lin_df, title_insight, title_desc, regime_tag, note, out_path):
    """Two-regime cumulative IRF in the house style: floated y-axis, direct end
    labels, 60% HAC bands, an annotated 24m hot-slack gap."""
    Z = 0.8416   # 60% band (two-sided normal), matching the note's headline chart
    s = sd_df.set_index("h"); l = lin_df.set_index("h")
    h = s.index.to_numpy()
    fig, ax = cs.figure(7.8, 6.1, rect=(0.055, 0.27, 0.80, 0.51))
    for beta, se, col in [(s.betaH, s.seH, HOT), (s.betaL, s.seL, SLACK)]:
        ax.fill_between(h, beta - Z * se, beta + Z * se, color=col, alpha=0.12, lw=0)
        ax.plot(h, beta, color=col, lw=2.3)
    ax.plot(l.index, l.beta, color=LIN, lw=1.5, ls=":")
    ax.axhline(0, color=cs.BASE, lw=0.8)
    ax.set_xlim(0, 26); ax.set_xticks([0, 6, 12, 18, 24])
    ax.set_xlabel("Months after the shock")
    ticks = _yticks(s.betaH - Z * s.seH, s.betaL - Z * s.seL,
                    s.betaH + Z * s.seH, s.betaL + Z * s.seL)
    cs.floated_yaxis(ax, ticks)
    ax.set_ylim(ticks.min(), ticks.max())      # tight to the data, no dead space up top
    # direct end-of-line labels (regime-aware; nudged apart so they never overlap)
    hard = "v/u = 1" in regime_tag
    tight_lab = "Tight (v/u ≥ 1)" if hard else "Tight labour market"
    slack_lab = "Slack (v/u < 1)" if hard else "Slack labour market"
    ends = [(tight_lab, s.betaH.iloc[-1], HOT),
            (slack_lab, s.betaL.iloc[-1], SLACK),
            ("Unconditional", l.beta.iloc[-1], LIN)]
    yy = cs.spread([e[1] for e in ends], 0.13 * (ax.get_ylim()[1] - ax.get_ylim()[0]))
    for (lab, _, col), y in zip(ends, yy):
        cs.direct_label(ax, 24.4, y, lab, col, size=8.5, bold=(col is not LIN))
    # gap stat, tucked into the empty upper-left (clear of the floated labels and the data)
    g12, p12 = s.loc[12, "diff"], s.loc[12, "wald_p"]
    g24, p24 = s.loc[24, "diff"], s.loc[24, "wald_p"]
    ax.text(0.13, 0.97, "Tight − slack gap\n"
            f"{g12:+.2f}pp at 12m (p={_pfmt(p12)})\n{g24:+.2f}pp at 24m (p={_pfmt(p24)})",
            transform=ax.transAxes, ha="left", va="top", ma="left", fontsize=7.8,
            family=cs.SANS, color=cs.INK, linespacing=1.4, zorder=8,
            bbox=dict(boxstyle="round,pad=0.5", facecolor="#F3EDE3", edgecolor="none", alpha=0.94))
    cs.title(fig, title_insight, title_desc)
    cs.source(fig, note + "\n" + SRC)
    cs.check_overlaps(fig, Path(out_path).name)
    z60, z90 = 0.8416, 1.645  # two-sided normal critical values
    chart_data = pd.DataFrame({
        "months_after_shock": s.index, "hot": s.betaH.values, "slack": s.betaL.values,
        "linear_no_state": l["beta"].reindex(s.index).values,
        "hot_lower60": (s.betaH - z60 * s.seH).values, "hot_upper60": (s.betaH + z60 * s.seH).values,
        "slack_lower60": (s.betaL - z60 * s.seL).values, "slack_upper60": (s.betaL + z60 * s.seL).values,
        "hot_lower90": (s.betaH - z90 * s.seH).values, "hot_upper90": (s.betaH + z90 * s.seH).values,
        "slack_lower90": (s.betaL - z90 * s.seL).values, "slack_upper90": (s.betaL + z90 * s.seL).values})
    chart_data.to_csv(out_path.replace(".png", "_data.csv"), index=False)
    fig.savefig(out_path); plt.close(fig)


def run_robustness(y, start, specs, h=24):
    rows = []
    for lbl, dd, F, sr, nl in specs:
        s = u.state_sign_lp(dd.loc[start:], y, "shock", F, [h], state_raw=sr, n_lags=nl).iloc[0]
        rows.append({"spec": lbl, "diff": s["diff"], "wald_p": s["wald_p"]})
    return pd.DataFrame(rows).set_index("spec")


def plot_robustness(rob, measure, sample_lbl, regime_tag, out_path, peak_note=""):
    """Signed horizontal bars: hot-slack gap across tightness measures and sample cuts,
    accent where significant at 10% (HAC Wald), muted otherwise."""
    r = rob.iloc[::-1]; yv = np.arange(len(r))
    fig, ax = cs.figure(7.8, 6.2, rect=(0.30, 0.22, 0.66, 0.52))
    ax.barh(yv, r["diff"], color=[cs.ACCENT if p < 0.1 else cs.MUTE for p in r.wald_p])
    ax.axvline(0, color=cs.BASE, lw=0.8)
    ax.set_yticks(yv); ax.set_yticklabels(r.index, fontsize=9)
    ax.spines["left"].set_visible(False); ax.tick_params(length=0)
    lo = min(r["diff"].min() - 0.12, -0.12); hi = r["diff"].max() + max(0.5, r["diff"].max() * 0.28)
    ax.set_xlim(lo, hi)
    for yy, dv, p in zip(yv, r["diff"], r.wald_p):
        # always place the p-label just right of zero (or the bar tip), left-aligned, so a
        # negative bar's label never runs left across the axis into the category tick labels
        ax.text(max(dv, 0.0) + 0.03, yy, f"p={_pfmt(p)}", va="center",
                ha="left", fontsize=7.5, color=cs.SUBTLE, family=cs.SANS)
    ax.set_xlabel("Hot minus slack response, pp (per +1 s.d. shock, at 24 months)")
    note = ("Note. Accent bars mark a hot-vs-slack difference significant at 10%% (HAC Wald). Sample %s.%s"
            % (sample_lbl, (" " + peak_note) if peak_note else ""))
    cs.title(fig, "Hot-minus-slack gap across tightness gauges and sample cuts",
             "%s, 24-month gap in pp (%s)" % (measure[:1].upper() + measure[1:], regime_tag))
    cs.source(fig, note + "\n" + SRC)
    cs.check_overlaps(fig, Path(out_path).name)
    fig.savefig(out_path); plt.close(fig)


def two_paradigm_irf(df, df_no2122, y, F, start, measure, regime_tag, out_path):
    sd_full = u.state_sign_lp(df.loc[start:], y, "shock", F, HORIZONS, state_raw="vu", n_lags=N_LAGS)
    sdx = u.state_sign_lp(df_no2122.loc[start:], y, "shock", F, HORIZONS, state_raw="vu", n_lags=N_LAGS)
    f, x = sd_full.set_index("h"), sdx.set_index("h"); h = f.index.to_numpy()
    fig, ax = cs.figure(7.8, 6.3, rect=(0.055, 0.25, 0.90, 0.47))
    ax.fill_between(h, f.betaH - 1.645 * f.seH, f.betaH + 1.645 * f.seH, color=HOT, alpha=0.10, lw=0)
    ax.plot(h, f.betaH, color=HOT, lw=2.4, label="Hot, full sample (2021-22 included)")
    ax.plot(x.index, x.betaH, color=HOT, lw=2.0, ls="--", label="Hot, excluding 2021-22 (clean supply)")
    ax.plot(h, f.betaL, color=SLACK, lw=1.9, label="Slack labour market")
    ax.axhline(0, color=cs.BASE, lw=0.8); ax.set_xlim(0, 24); ax.set_xticks([0, 6, 12, 18, 24])
    ax.set_xlabel("Months after the shock")
    cs.floated_yaxis(ax, _yticks(f.betaH - 1.645 * f.seH, f.betaH + 1.645 * f.seH, f.betaL, x.betaH))
    cs.legend(ax, above=True)
    g24f = f.betaH.iloc[-1] - f.betaL.iloc[-1]; g24x = x.betaH.iloc[-1] - x.betaL.iloc[-1]
    note = ("Note. Cumulative price response to a price-raising oil-supply shock, per +1 s.d. The hot-regime "
            "response on the full sample versus excluding 2021-22 isolates whether the amplification depends on "
            "that episode. 24-month hot-slack gap: full %.2f, excluding 2021-22 %.2f." % (g24f, g24x))
    cs.title(fig, "The hot-regime response, with and without the 2021-22 episode",
             "%s, cumulative price response in %% (%s)" % (measure[:1].upper() + measure[1:], regime_tag))
    cs.source(fig, note + "\n" + SRC)
    cs.check_overlaps(fig, Path(out_path).name)
    fig.savefig(out_path); plt.close(fig)
    out = pd.DataFrame({"h": f.index, "hot_full": f.betaH.values, "hot_ex2122": x.betaH.reindex(f.index).values,
                        "slack": f.betaL.values})
    return out, g24f, g24x


