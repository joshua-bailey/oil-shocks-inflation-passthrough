def _pfmt(p):
    """p-value label: avoid a misleading '0.00' for very small p."""
    return "<0.01" if p < 0.005 else f"{p:.2f}"


def _yticks(*arrays, n=4):
    """Sparse, honest y ticks tight to the plotted arrays (straddling 0, minimal overshoot)."""
    vals = np.concatenate([np.asarray(a, float).ravel() for a in arrays])
    lo, hi = min(np.nanmin(vals), 0.0), max(np.nanmax(vals), 0.0)
    rng = (hi - lo) or 1.0
    ticks = MaxNLocator(n).tick_values(lo, hi)
    ticks = ticks[(ticks >= lo - 0.12 * rng) & (ticks <= hi + 0.18 * rng)]
    if 0.0 not in ticks:
        ticks = np.sort(np.append(ticks, 0.0))
    return ticks


