"""Regenerate the regime-sensitive charts for every gauge, on both regime definitions.

For each measure (CPI supercore, core PCE, market-based core PCE) this writes:
  - the MAIN result (hard v/u=1 threshold) to the measure-folder top level, and
  - the ROBUSTNESS cross-check (logistic, mean-centred) to a robustness_logistic/ subfolder,
each comprising the state-dependent IRF chart (+ _data.csv), the nine-spec robustness panel
(fig3) + robustness_grid.csv, the drop-2021-22 two-paradigms chart (fig11) + two_paradigms_data.csv,
and the point-IRF / linear-baseline CSVs.

The regime-independent / cross-measure figures (continuous-interaction passthrough curve fig4,
market-price ladder fig9, paradigm map fig10, and the CPI component attribution fig2/2b) are
generated by analysis.ipynb, not here.

Reuses the canonical estimators in svar_lp_utils.py; rebuilds the panel from data_cache so the
script is reproducible without the notebook. Run:  python regime_comparison.py
"""
